"""Generate c/tables.h from mitalk/tables.py (itself generated from the book).

    python tools/gen_c_tables.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from mitalk import tables as T  # noqa: E402

# Segment symbols: everything with targets, in a fixed order.
SEGS = sorted(T.TARGETS)
CLASSES = sorted(T.CLASSES)
TARGET_COLS = ("av", "avc", "asp", "af", "a2", "a3", "a4", "a5", "a6", "ab",
               "f1", "f2", "f3", "f4", "b1", "b2", "b3")
PARS = ("av", "avc", "asp", "af", "a2p", "a3p", "a4p", "a5p", "a6p", "ab",
        "an", "f1", "f2", "f3", "f4", "fnz", "b1", "b2", "b3")
MANNERS = ("vowel", "stop", "fricative", "sonorant")


def main():
    out = ["/* Data tables from the MITalk book.  GENERATED by tools/gen_c_tables.py",
           " * from mitalk/tables.py -- do not edit by hand. */",
           "#ifndef MITALK_TABLES_H", "#define MITALK_TABLES_H", ""]
    out.append(f"#define NSEG {len(SEGS)}")
    out.append("enum seg { " + ", ".join(f"S_{s}" for s in SEGS) + " };")
    out.append("static const char *const SEG_NAME[NSEG] = { " +
               ", ".join(f'"{s}"' for s in SEGS) + " };")
    out.append("")
    out.append(f"#define NCLASS {len(CLASSES)}")
    out.append("enum cls { " + ", ".join(f"C_{c.upper()}" for c in CLASSES) + " };")
    out.append("static const char *const CLASS_NAME[NCLASS] = { " +
               ", ".join(f'"{c}"' for c in CLASSES) + " };")
    out.append("/* bit (1u << C_x) set if the segment belongs to class x (Appendix C.3) */")
    masks = []
    for s in SEGS:
        bits = [f"(1u<<C_{c.upper()})" for c in CLASSES if s in T.CLASSES[c]]
        masks.append(" | ".join(bits) if bits else "0")
    out.append("static const unsigned SEG_CLASSES[NSEG] = {\n    " +
               ",\n    ".join(f"/* {s} */ {m}" for s, m in zip(SEGS, masks)) + "\n};")
    out.append("")
    out.append("/* Tables C-1 / C-2 columns: " + " ".join(TARGET_COLS) + " */")
    out.append(f"#define NTGT {len(TARGET_COLS)}")
    out.append("static const short TARGET[NSEG][NTGT] = {\n" + ",\n".join(
        f"    /* {s:3s} */ {{" + ", ".join(str(T.TARGETS[s][c]) for c in TARGET_COLS) + "}"
        for s in SEGS) + "\n};")
    out.append("/* second (offglide) f1 f2 f3 row of Table C-2; 0 = none */")
    out.append("static const short DIPTAR[NSEG][3] = {\n" + ",\n".join(
        f"    /* {s:3s} */ {{" + ", ".join(str(v) for v in T.DIPTAR.get(s, (0, 0, 0))) + "}"
        for s in SEGS) + "\n};")
    out.append("/* Table C-5 (Tcdiph, Tdmid); -1 = not listed */")
    out.append("static const short DIPHTHONG[NSEG][2] = {\n" + ",\n".join(
        f"    /* {s:3s} */ {{" + ", ".join(str(v) for v in T.DIPHTHONG.get(s, (-1, -1))) + "}"
        for s in SEGS) + "\n};")
    out.append("/* Table C-6 Tcobst; -1 = not listed */")
    out.append("static const short TCOBST[NSEG] = { " +
               ", ".join(str(T.TCOBST.get(s, -1)) for s in SEGS) + " };")
    out.append("/* Table C-7 Burdur; 0 = not listed */")
    out.append("static const short BURDUR[NSEG] = { " +
               ", ".join(str(T.BURDUR.get(s, 0)) for s in SEGS) + " };")
    out.append("/* Table 9-1 (MINDUR, INHDUR); -1 = not listed */")
    out.append("static const short DURATIONS[NSEG][2] = {\n" + ",\n".join(
        f"    /* {s:3s} */ {{" + ", ".join(str(v) for v in T.DURATIONS.get(s, (-1, -1))) + "}"
        for s in SEGS) + "\n};")
    out.append("")
    out.append("/* PHONET parameter order (Appendix C names; f0 drawn separately) */")
    out.append(f"#define NPAR {len(PARS)}")
    out.append("enum par { " + ", ".join(f"P_{p.upper()}" for p in PARS) + " };")
    out.append("static const char *const PAR_NAME[NPAR] = { " +
               ", ".join(f'"{p}"' for p in PARS) + " };")
    out.append("/* Table C-3 Tcf defaults, in PHONET parameter order */")
    out.append("static const short TCF_DEFAULT[NPAR] = { " +
               ", ".join(str(T.TCF_DEFAULT[p]) for p in PARS) + " };")
    out.append("enum manner { " + ", ".join(f"M_{m.upper()}" for m in MANNERS) + " };")
    out.append("/* Table C-4 Bper defaults [previous manner][current manner] */")
    out.append("static const short BPER_DEFAULT[4][4] = {\n" + ",\n".join(
        "    {" + ", ".join(str(T.BPER_DEFAULT[(a, b)]) for b in MANNERS) + "}" for a in MANNERS)
        + "\n};")
    out.append("")
    out.append("#endif")
    (ROOT / "c" / "tables.h").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote c/tables.h:", len(SEGS), "segments,", len(CLASSES), "classes")


if __name__ == "__main__":
    main()
