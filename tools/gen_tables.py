"""Generate mitalk/tables.py from the book transcriptions in docs/book/.

Run from the project root:  python tools/gen_tables.py
Keeping the numbers machine-copied from the transcription avoids retyping
errors; edit the markdown (against the scans), not the generated file.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPC = (ROOT / "docs/book/appendix_c_phonet_rules.md").read_text(encoding="utf-8")
CH9 = (ROOT / "docs/book/ch09_durations.md").read_text(encoding="utf-8")


def table_after(text, title):
    """Rows (lists of cell strings) of the first markdown table after title."""
    start = text.index(title)
    rows = []
    for line in text[start:].splitlines()[1:]:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if not set("".join(cells)) <= set("-: "):
                rows.append(cells)
        elif rows:
            break
    return rows[0], rows[1:]


def num(s):
    return int(s) if s else None


def targets(title):
    header, rows = table_after(APPC, title)
    cols = header[1:]
    main, second = {}, {}
    for r in rows:
        name = r[0]
        if name.endswith("(2nd)"):
            second[name.split()[0]] = tuple(num(r[1 + cols.index(c)])
                                            for c in ("f1", "f2", "f3"))
        else:
            main[name] = {c: num(v) for c, v in zip(cols, r[1:])}
    return main, second


def pairs(title):
    """Tables printed as repeated (name, value[, value]) column groups."""
    header, rows = table_after(APPC, title)
    width = 1
    while width < len(header) and header[width] != header[0]:
        width += 1
    out = {}
    for r in rows:
        for i in range(0, len(r), width):
            if r[i]:
                vals = tuple(num(v) for v in r[i + 1:i + width])
                out[r[i]] = vals[0] if len(vals) == 1 else vals
    return out


def classes():
    out = {}
    for line in APPC[APPC.index("### C.3"):APPC.index("### C.4")].splitlines():
        m = re.match(r"\| (\w+) \| ([A-Z, ]+?)\s*(\(|\|)", line + " |")
        if m and m.group(1) != "class":
            out[m.group(1)] = sorted(set(re.findall(r"[A-Z]+", m.group(2))))
    return out


def durations():
    _, rows = table_after(CH9, "## Table 9-1")
    return {r[1]: (int(r[2]), int(r[3])) for r in rows}


def bper():
    header, rows = table_after(APPC, "**Table C-4")
    return {(r[0], c): int(v) for r in rows for c, v in zip(header[1:], r[1:])}


def main():
    nonvoc, _ = targets("**Table C-1")
    voc, diptar = targets("**Table C-2")
    out = ['"""Data tables from the MITalk book.  GENERATED by tools/gen_tables.py',
           'from docs/book/*.md -- do not edit by hand."""', ""]
    out.append(f"TARGETS = {dict(nonvoc, **voc)!r}")
    out.append(f"DIPTAR = {diptar!r}")
    out.append(f"CLASSES = {classes()!r}")
    out.append(f"TCF_DEFAULT = {pairs('**Table C-3')!r}")
    out.append(f"BPER_DEFAULT = {bper()!r}")
    out.append(f"DIPHTHONG = {pairs('**Table C-5')!r}  # seg: (Tcdiph, Tdmid)")
    out.append(f"TCOBST = {pairs('**Table C-6')!r}")
    out.append(f"BURDUR = {pairs('**Table C-7')!r}")
    out.append(f"DURATIONS = {durations()!r}  # seg: (MINDUR, INHDUR)")
    (ROOT / "mitalk/tables.py").write_text("\n\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
